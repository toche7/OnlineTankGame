// Language Manager
class LanguageManager {
  constructor() {
    this.currentLang = localStorage.getItem('gameLanguage') || 'th'; // Default to Thai
    this.translations = translations;
  }
  
  setLanguage(lang) {
    if (this.translations[lang]) {
      this.currentLang = lang;
      localStorage.setItem('gameLanguage', lang);
      this.updatePage();
      return true;
    }
    return false;
  }
  
  t(key) {
    return this.translations[this.currentLang][key] || key;
  }
  
  getCurrentLanguage() {
    return this.currentLang;
  }
  
  updatePage() {
    // Update all elements with data-i18n attribute
    document.querySelectorAll('[data-i18n]').forEach(element => {
      const key = element.getAttribute('data-i18n');
      const translation = this.t(key);
      
      if (element.tagName === 'INPUT' && element.type !== 'checkbox' && element.type !== 'number') {
        element.placeholder = translation;
      } else if (element.tagName === 'OPTION') {
        element.textContent = translation;
      } else {
        element.textContent = translation;
      }
    });
    
    // Update page title
    const h1 = document.querySelector('h1');
    if (h1) {
      document.title = `${this.t('gameTitle')} - Menu`;
    }
    
    // Update How to Play list if exists
    const howToPlayList = document.querySelector('.info-section ul');
    if (howToPlayList) {
      const items = this.t('howToPlayItems');
      if (Array.isArray(items)) {
        howToPlayList.innerHTML = items.map(item => `<li>${item}</li>`).join('');
      }
    }
    
    // Update language selector to show current selection
    document.querySelectorAll('.lang-btn').forEach(btn => {
      if (btn.getAttribute('data-lang') === this.currentLang) {
        btn.classList.add('active');
      } else {
        btn.classList.remove('active');
      }
    });
    // Update toggle button if present
    const toggle = document.getElementById('langToggleBtn');
    if (toggle) {
      const code = this.currentLang || 'th';
      const opposite = (code === 'en') ? 'TH' : 'EN';
      toggle.textContent = opposite;
      toggle.setAttribute('aria-pressed', String(code !== 'en'));
    }
  }
}

// Create global language manager instance
const langManager = new LanguageManager();

// Initialize on page load
if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', () => {
    langManager.updatePage();
  });
} else {
  langManager.updatePage();
}
